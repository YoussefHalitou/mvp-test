#!/bin/bash

# Script zum Einrichten von Nginx mit SSL für chatbotcarsten.live

set -e

DOMAIN="chatbotcarsten.live"

echo "🔧 Konfiguriere Nginx für $DOMAIN..."

# Erstelle Nginx-Konfiguration
cat > /etc/nginx/sites-available/medical-chatbot << EOF
server {
    listen 80;
    server_name $DOMAIN;
    return 301 https://\$server_name\$request_uri;
}

server {
    listen 443 ssl http2;
    server_name $DOMAIN;

    ssl_certificate /etc/letsencrypt/live/$DOMAIN/fullchain.pem;
    ssl_certificate_key /etc/letsencrypt/live/$DOMAIN/privkey.pem;
    
    ssl_protocols TLSv1.2 TLSv1.3;
    ssl_ciphers HIGH:!aNULL:!MD5;
    ssl_prefer_server_ciphers on;

    # Frontend
    location / {
        proxy_pass http://localhost:3000;
        proxy_http_version 1.1;
        proxy_set_header Upgrade \$http_upgrade;
        proxy_set_header Connection 'upgrade';
        proxy_set_header Host \$host;
        proxy_set_header X-Real-IP \$remote_addr;
        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto \$scheme;
        proxy_cache_bypass \$http_upgrade;
    }

    # Backend API
    location /api {
        proxy_pass http://localhost:8000;
        proxy_http_version 1.1;
        proxy_set_header Upgrade \$http_upgrade;
        proxy_set_header Connection 'upgrade';
        proxy_set_header Host \$host;
        proxy_set_header X-Real-IP \$remote_addr;
        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto \$scheme;
        proxy_cache_bypass \$http_upgrade;
    }

    # WebSocket Support
    location /ws {
        proxy_pass http://localhost:8000;
        proxy_http_version 1.1;
        proxy_set_header Upgrade \$http_upgrade;
        proxy_set_header Connection "upgrade";
        proxy_set_header Host \$host;
        proxy_set_header X-Real-IP \$remote_addr;
        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto \$scheme;
    }
}
EOF

# Aktiviere Konfiguration
ln -sf /etc/nginx/sites-available/medical-chatbot /etc/nginx/sites-enabled/
rm -f /etc/nginx/sites-enabled/default

# Teste Konfiguration
echo "🧪 Teste Nginx-Konfiguration..."
nginx -t

# Starte Nginx neu
echo "🔄 Starte Nginx neu..."
systemctl restart nginx

echo ""
echo "✅ Nginx erfolgreich konfiguriert!"
echo ""
echo "🌐 Teste jetzt:"
echo "   https://$DOMAIN"
echo "   https://$DOMAIN/api/health"
echo ""

